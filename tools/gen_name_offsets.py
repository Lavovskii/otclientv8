#!/usr/bin/env python3
"""How tall every looktype is drawn, for modules/game_nameoffset: writes modules/game_nameoffset/heights.lua.

The client draws a creature's name and health bar at the same height whatever its outfit, right for a one-tile
outfit and inside the body of a big one. For every looktype this measures, facing south, standing, with any addon,
how many pixels the picture rises above the bottom of its frame (unmounted, and mounted when it has a mounted
picture); the module raises the name of the looktypes taller than the Citizen. Only numbers are written.

  python tools/gen_name_offsets.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CLIENT = os.path.join(HERE, '..')
sys.path.insert(0, os.path.join(CLIENT, '..', 'ForgottenL', 'tools'))
import gen_the860_looktypes as L  # noqa: E402

THINGS = os.path.join(CLIENT, 'data', 'things', '860')
OUT = os.path.join(CLIENT, 'modules', 'game_nameoffset', 'heights.lua')
REFERENCE = 128  # the Citizen: names stay where they are for it and anything not taller


def height(outfit, sprites, z):
    """pixels from the frame's bottom to the highest drawn pixel, facing south, phase 0, any addon (0: nothing drawn)"""
    w, h, layers, px, py = outfit['w'], outfit['h'], outfit['layers'], outfit['px'], outfit['py']
    x = 2 if px >= 3 else 0
    best = 0
    for y in range(py):
        for hy in range(h):
            for wx in range(w):
                index = ((((z * py + y) * px + x) * layers + 0) * h + hy) * w + wx
                if index >= len(outfit['sprites']):
                    continue
                sprite = sprites.image(outfit['sprites'][index])
                if not sprite:
                    continue
                box = sprite.getbbox()
                if box:
                    top = (h - 1 - hy) * 32 + box[1]  # row of the highest pixel in the frame
                    best = max(best, h * 32 - top)
    return best


def main():
    outfits = L.read_outfits(os.path.join(THINGS, 'Tibia.dat'))
    sprites = L.Sprites(os.path.join(THINGS, 'Tibia.spr'))
    reference = height(outfits[REFERENCE], sprites, 0)
    lines, mounted_lines = [], []
    for tid in sorted(outfits):
        o = outfits[tid]
        if o['w'] == 1 and o['h'] == 1:
            continue  # a one-tile outfit can't be taller than the Citizen's frame allows
        h0 = height(o, sprites, 0)
        if h0 > reference:
            lines.append('  [%d] = %d,' % (tid, h0))
        if o['pz'] > 1:
            h1 = height(o, sprites, 1)
            if h1 > reference:
                mounted_lines.append('  [%d] = %d,' % (tid, h1))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- Generated by tools/gen_name_offsets.py: pixels each looktype rises above the bottom of its frame,\n')
        f.write('-- facing south with any addon, only those taller than the Citizen (looktype %d, %d px).\n' % (REFERENCE, reference))
        f.write('NAME_OFFSET_REFERENCE = %d\n' % reference)
        f.write('NAME_OFFSET_HEIGHTS = {\n%s\n}\n' % '\n'.join(lines))
        f.write('-- the same for the looktype drawn mounted (its mounted pictures)\n')
        f.write('NAME_OFFSET_MOUNTED = {\n%s\n}\n' % '\n'.join(mounted_lines))
    print('reference', reference, 'taller', len(lines), 'mounted taller', len(mounted_lines))


if __name__ == '__main__':
    main()
