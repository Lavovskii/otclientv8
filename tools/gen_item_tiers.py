#!/usr/bin/env python3
"""Which items have a tier, for modules/game_tiers: reads the server's items.xml ("tier" attribute) and items.otb (server
id -> client id) and writes modules/game_tiers/tiers_data.lua, ITEM_TIERS = {[client id] = tier}. Run it again whenever
the server's items change.

  python tools/gen_item_tiers.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SERVER_TOOLS = os.path.join(HERE, '..', '..', 'ForgottenL', 'tools')
sys.path.insert(0, SERVER_TOOLS)
import gen_item_client_map as otbmap  # noqa: E402
import items_xml  # noqa: E402

OUT = os.path.join(HERE, '..', 'modules', 'game_tiers', 'tiers_data.lua')


def main():
    client = dict(otbmap.items(open(otbmap.OTB, 'rb').read()))
    tiers = {}
    for e in items_xml.elements():
        attrs = {c.get('key'): c.get('value') for c in e.findall('attribute')}
        tier = attrs.get('tier')
        if not tier or not tier.isdigit():
            continue
        ids = []
        if 'id' in e.attrib:
            ids = [int(e.attrib['id'])]
        elif 'fromid' in e.attrib:
            ids = range(int(e.attrib['fromid']), int(e.attrib['toid']) + 1)
        for sid in ids:
            cid = client.get(sid)
            if cid:
                tiers[cid] = int(tier)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- Generated by tools/gen_item_tiers.py from the server\'s items.xml: client item id -> tier (1-6)\n')
        f.write('ITEM_TIERS = {\n')
        for cid in sorted(tiers):
            f.write('  [%d] = %d,\n' % (cid, tiers[cid]))
        f.write('}\n')
    print(len(tiers), 'items with a tier')


if __name__ == '__main__':
    main()
