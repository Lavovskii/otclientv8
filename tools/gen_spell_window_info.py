#!/usr/bin/env python3
"""Writes modules/game_spelllist/spellwindowinfo.lua: what the Spells window shows of each vocation area spell besides
the client's spell list (gamelib/spells.lua): its design for the demo, element, damage area, waves and the level where
the next spell of the vocation comes (the server stops counting the level there, data/lib/139-vocation-spells.lua
vocationSpellLevelCap). Read from the server repository's tools/vocation_spells.json and vocation_spells_designs.json
(made by its tools/make_vocation_spells_spec.py and the map editor's harness). Run from the client's root after the
vocation spells change (the server repository is expected next to this one):

    python tools/gen_spell_window_info.py [path to the server repository]
"""
import json
import os
import sys

CLIENT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SERVER = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(CLIENT, '..', 'ForgottenL'))
OUT = os.path.join(CLIENT, 'modules', 'game_spelllist', 'spellwindowinfo.lua')


def lua_string(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    spec = json.load(open(os.path.join(SERVER, 'tools', 'vocation_spells.json'), encoding='utf8'))
    designs = json.load(open(os.path.join(SERVER, 'tools', 'vocation_spells_designs.json'), encoding='utf8'))
    by_id = {d['id']: d for d in designs['spells']}
    levels = [t[0] for t in spec['tiers']]

    lines = ['-- Generated by tools/gen_spell_window_info.py from the server\'s tools/vocation_spells.json and',
             '-- vocation_spells_designs.json: change those, not this file. Per vocation area spell (by name): its design in',
             '-- game_spellfx (SPELLFX_DESIGNS), vocation, element, damage area (shape, radius, the tiles it hits around the',
             '-- caster as a flat {x1, y1, x2, y2, ...} list), waves, when the last wave lands (ms) and the level where the next',
             '-- spell comes (the level counts up to there; nil for the last one).',
             'SpellWindowInfo = {']
    for s in spec['spells']:
        design = by_id.get(s['id'], {})
        tiles = design.get('damage_tiles') or []
        flat = ', '.join('%d, %d' % (x, y) for x, y in tiles)
        tier = levels.index(s['level']) if s['level'] in levels else -1
        nxt = levels[tier + 1] if 0 <= tier < len(levels) - 1 else None
        lines.append('  [%s] = {design = %s, vocation = %s, element = %s, shape = %s, radius = %d, waves = %d, ends = %d,'
                     % (lua_string(s['name']), lua_string(s['id']), lua_string(s['vocation']), lua_string(s['element']),
                        lua_string(s['shape']), s['radius'], len(design.get('pulses') or []) or s['pulses'],
                        int(design.get('end_ms') or 0)))
        lines.append('    nextLevel = %s, tiles = {%s}},' % ('nil' if nxt is None else nxt, flat))
    lines.append('}')
    open(OUT, 'w', encoding='utf8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(spec['spells']), 'spells')


if __name__ == '__main__':
    sys.exit(main())
